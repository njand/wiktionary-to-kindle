"""Forms added to an entry during merge_dump, from what its own forms already say.

The regular forms an entry's forms imply (for Latin, the declension of a participle or
comparative Wiktionary lists only in the nominative) are generated by its language
(Language.implied_forms) and added to the entry, each form tagged "generated". A form whose
page exists is left alone: that page is merged in (or is an entry of its own), and a second
copy of its labels would only list both in the popup.

Alternative spellings (inlābor beside illābor) are kept as labels, except those with a page
of their own, for the same reason, and reconstructions (*luttra), which no text spells.
"""

from ..utils import remove_breves

GENERATED = "generated"


def enrich_forms(forms, known, language, merged=(), entry=None):
    """Return an entry's own forms, less alternative spellings that have a page (known holds
    the dump's headwords without breves), then the forms merged from pages that point to it,
    then the forms these imply (entry: the page, for forms its headword implies)."""
    forms = [
        form
        for form in forms
        if not _redundant_alternative(form, known, language.alternative_tags)
    ]
    forms += merged
    implied = language.implied_forms(forms, known, entry or {})

    have = {form.get("form") for form in forms}
    generated = []
    for spelling, tags in implied:
        if spelling not in have:
            have.add(spelling)
            generated.append({"form": spelling, "tags": [*tags, GENERATED]})
    return forms + generated


def _redundant_alternative(form, known, alternative_tags):
    tags = set(form.get("tags", []))
    if not tags & alternative_tags:
        return False
    word = form.get("form", "")
    return (
        "reconstruction" in tags or word.startswith("*") or remove_breves(word) in known
    )
